/** route("日本 → 韓国") 에서 도착 시장을 뽑는다. 케이스 상세 배경 사진에 쓴다. */
export function destOf(route: string): 'kr' | 'jp' | 'tw' {
  const dest = route.split('→').pop() ?? '';
  if (/韓国|한국|韓國/.test(dest)) return 'kr';
  if (/台湾|대만|台灣/.test(dest)) return 'tw';
  return 'jp';
}

/**
 * 그 경로가 실제로 존재하는 언어만 돌려준다.
 *
 * 케이스 상세(/works/<slug>)는 번역이 있는 언어에만 생성된다.
 * 이걸 무시하고 3개 언어를 다 뿌리면
 *   - 푸터 언어 전환이 404 로 떨어지고
 *   - hreflang 이 없는 페이지를 가리켜 색인 오류가 난다.
 * 검색·AI 에 읽히는 상태를 만드는 게 이 사이트의 목적이므로, 여기서 막는다.
 */
export function langsFor(path: string): Lang[] {
  const m = path.match(/^\/works\/([^/]+)\/?$/);
  if (!m) return [...LANGS];
  return LANGS.filter((l) => getCases(l).some((c) => c.slug === m[1]));
}
